-- updated_at
create or replace function public.sett_updated_at() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;

do $$ declare t text; begin
  foreach t in array array['profiles','eiendommer','leietakere','systemer','komponenter','oppgaver','avvik','dokumenter','tegninger'] loop
    execute format('drop trigger if exists %I_updated on public.%I', t, t);
    execute format('create trigger %I_updated before update on public.%I for each row execute function public.sett_updated_at()', t, t);
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- Hjelpefunksjoner for tilgang (security definer = leser profiles uten RLS-sløyfe)
-- ---------------------------------------------------------------------
create or replace function public.min_rolle() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select case when aktiv then rolle else 'ingen' end from profiles where id = auth.uid()), 'ingen')
$$;

create or replace function public.er_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select public.min_rolle() = 'admin'
$$;

-- Ansatte (forvalter/tekniker) med tilgang til eiendommen, eller admin
create or replace function public.har_eiendom(eid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select case public.min_rolle()
    when 'admin' then true
    when 'forvalter' then exists (select 1 from eiendom_tilgang where user_id = auth.uid() and eiendom_id = eid)
    when 'tekniker'  then exists (select 1 from eiendom_tilgang where user_id = auth.uid() and eiendom_id = eid)
    else false end
$$;

-- Kan endre fagdata på eiendommen (admin, eller forvalter med tilgang)
create or replace function public.kan_redigere(eid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select case public.min_rolle()
    when 'admin' then true
    when 'forvalter' then exists (select 1 from eiendom_tilgang where user_id = auth.uid() and eiendom_id = eid)
    else false end
$$;

create or replace function public.mitt_leietaker_id() returns uuid
language sql stable security definer set search_path = public as $$
  select case when public.min_rolle() = 'leietaker' then (select leietaker_id from profiles where id = auth.uid()) else null end
$$;

create or replace function public.min_leietaker_eiendom() returns uuid
language sql stable security definer set search_path = public as $$
  select eiendom_id from leietakere where id = public.mitt_leietaker_id()
$$;

-- ---------------------------------------------------------------------
-- Ny bruker → profil. Første bruker i systemet blir administrator.
-- Andre får rollen 'ingen' til en administrator tildeler rolle.
-- ---------------------------------------------------------------------
create or replace function public.ny_bruker() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, epost, navn, rolle)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'navn', split_part(new.email,'@',1)),
          case when exists (select 1 from profiles where rolle = 'admin') then 'ingen' else 'admin' end)
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.ny_bruker();

