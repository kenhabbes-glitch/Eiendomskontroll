-- profiles: egen profil + admin ser alle; ansatte ser navn på kolleger med felles eiendom
create policy profiles_select on public.profiles for select using (
  id = auth.uid() or public.er_admin()
  or (public.min_rolle() in ('forvalter','tekniker') and rolle in ('admin','forvalter','tekniker'))
);
create policy profiles_admin_update on public.profiles for update using (public.er_admin()) with check (public.er_admin());
create policy profiles_admin_delete on public.profiles for delete using (public.er_admin() and id <> auth.uid());

-- eiendom_tilgang
create policy tilgang_select on public.eiendom_tilgang for select using (public.er_admin() or user_id = auth.uid());
create policy tilgang_admin_all on public.eiendom_tilgang for all using (public.er_admin()) with check (public.er_admin());

-- eiendommer
create policy eiendom_select on public.eiendommer for select using (
  public.har_eiendom(id) or id = public.min_leietaker_eiendom());
create policy eiendom_insert on public.eiendommer for insert with check (public.er_admin());
create policy eiendom_update on public.eiendommer for update using (public.kan_redigere(id)) with check (public.kan_redigere(id));
create policy eiendom_delete on public.eiendommer for delete using (public.er_admin());

-- leietakere: forvalter/admin; leietaker ser egen rad (endrer via funksjon)
create policy leietaker_select on public.leietakere for select using (
  public.kan_redigere(eiendom_id) or id = public.mitt_leietaker_id());
create policy leietaker_write on public.leietakere for insert with check (public.kan_redigere(eiendom_id));
create policy leietaker_update on public.leietakere for update using (public.kan_redigere(eiendom_id)) with check (public.kan_redigere(eiendom_id));
create policy leietaker_delete on public.leietakere for delete using (public.kan_redigere(eiendom_id));

-- systemer og komponenter: ansatte leser, forvalter/admin endrer
create policy system_select on public.systemer for select using (public.har_eiendom(eiendom_id));
create policy system_insert on public.systemer for insert with check (public.kan_redigere(eiendom_id));
create policy system_update on public.systemer for update using (public.kan_redigere(eiendom_id)) with check (public.kan_redigere(eiendom_id));
create policy system_delete on public.systemer for delete using (public.kan_redigere(eiendom_id));

create policy komp_select on public.komponenter for select using (public.har_eiendom(eiendom_id));
create policy komp_insert on public.komponenter for insert with check (public.kan_redigere(eiendom_id));
create policy komp_update on public.komponenter for update using (public.kan_redigere(eiendom_id)) with check (public.kan_redigere(eiendom_id));
create policy komp_delete on public.komponenter for delete using (public.kan_redigere(eiendom_id));

-- oppgaver (kontroller): tekniker kan registrere utført (update)
create policy oppg_select on public.oppgaver for select using (public.har_eiendom(eiendom_id));
create policy oppg_insert on public.oppgaver for insert with check (public.kan_redigere(eiendom_id));
create policy oppg_update on public.oppgaver for update using (public.har_eiendom(eiendom_id)) with check (public.har_eiendom(eiendom_id));
create policy oppg_delete on public.oppgaver for delete using (public.kan_redigere(eiendom_id));

-- avvik: ansatte med tilgang; leietaker ser og melder egne
create policy avvik_select on public.avvik for select using (
  public.har_eiendom(eiendom_id) or (leietaker_id is not null and leietaker_id = public.mitt_leietaker_id()));
create policy avvik_insert on public.avvik for insert with check (
  public.har_eiendom(eiendom_id)
  or (leietaker_id = public.mitt_leietaker_id() and eiendom_id = public.min_leietaker_eiendom()
      and coalesce(data->>'status','Ny') = 'Ny'));
create policy avvik_update on public.avvik for update using (public.har_eiendom(eiendom_id)) with check (public.har_eiendom(eiendom_id));
create policy avvik_delete on public.avvik for delete using (public.kan_redigere(eiendom_id));

-- dokumenter: tekniker ser ikke leietakerdokumenter og fortrolige typer
create policy dok_select on public.dokumenter for select using (
  public.kan_redigere(eiendom_id)
  or (public.min_rolle() = 'tekniker' and public.har_eiendom(eiendom_id) and leietaker_id is null
      and coalesce(data->>'type','') not in ('Leieavtale','Forsikringspolise','Samordningsavtale','Leietakers IK-dokumentasjon'))
  or (leietaker_id is not null and leietaker_id = public.mitt_leietaker_id()));
create policy dok_insert on public.dokumenter for insert with check (
  public.kan_redigere(eiendom_id)
  or (public.min_rolle() = 'tekniker' and public.har_eiendom(eiendom_id) and leietaker_id is null)
  or (leietaker_id = public.mitt_leietaker_id() and eiendom_id = public.min_leietaker_eiendom()));
create policy dok_update on public.dokumenter for update using (public.kan_redigere(eiendom_id)) with check (public.kan_redigere(eiendom_id));
create policy dok_delete on public.dokumenter for delete using (public.kan_redigere(eiendom_id));

-- tegninger: ansatte leser, forvalter/admin endrer
create policy teg_select on public.tegninger for select using (public.har_eiendom(eiendom_id));
create policy teg_insert on public.tegninger for insert with check (public.kan_redigere(eiendom_id));
create policy teg_update on public.tegninger for update using (public.kan_redigere(eiendom_id)) with check (public.kan_redigere(eiendom_id));
create policy teg_delete on public.tegninger for delete using (public.kan_redigere(eiendom_id));

-- ---------------------------------------------------------------------
-- Funksjoner leietaker kan kalle (endrer bare egne felter)
-- ---------------------------------------------------------------------
create or replace function public.bekreft_plikt(p_key text, p_dato date, p_kommentar text, p_dok uuid default null)
returns void language plpgsql security definer set search_path = public as $$
declare lid uuid := public.mitt_leietaker_id(); pl jsonb; i int; funnet boolean := false;
begin
  if lid is null then raise exception 'Ingen tilgang'; end if;
  select coalesce(data->'plikter','[]'::jsonb) into pl from leietakere where id = lid;
  for i in 0 .. jsonb_array_length(pl) - 1 loop
    if pl->i->>'key' = p_key then
      pl := jsonb_set(pl, array[i::text], (pl->i) || jsonb_build_object(
        'sist', p_dato, 'komm', p_kommentar, 'form', 'Bekreftet av leietaker',
        'dokId', p_dok, 'bekreftetAvLeietaker', true, 'bekreftetTid', now()));
      funnet := true;
    end if;
  end loop;
  if not funnet then raise exception 'Fant ikke plikten'; end if;
  update leietakere set data = jsonb_set(data, '{plikter}', pl) where id = lid;
end $$;

create or replace function public.oppdater_min_profil(p_navn text) returns void
language sql security definer set search_path = public as $$
  update profiles set navn = p_navn where id = auth.uid();
$$;

revoke all on function public.bekreft_plikt(text,date,text,uuid) from public, anon;
grant execute on function public.bekreft_plikt(text,date,text,uuid) to authenticated;
grant execute on function public.oppdater_min_profil(text) to authenticated;

-- ---------------------------------------------------------------------
-- Fillagring: privat bøtte «filer». Sti: {eiendom_id}/felles/... eller
-- {eiendom_id}/leietaker/{leietaker_id}/...
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('filer', 'filer', false, 52428800)
on conflict (id) do nothing;

create or replace function public.kan_lese_fil(p_name text) returns boolean
language sql stable security definer set search_path = public as $$
  select case
    when public.min_rolle() in ('admin','forvalter') then
      exists (select 1 from eiendommer e where e.id::text = split_part(p_name,'/',1) and public.kan_redigere(e.id))
    when public.min_rolle() = 'tekniker' then
      split_part(p_name,'/',2) <> 'leietaker'
      and exists (select 1 from eiendommer e where e.id::text = split_part(p_name,'/',1) and public.har_eiendom(e.id))
    when public.min_rolle() = 'leietaker' then
      split_part(p_name,'/',2) = 'leietaker' and split_part(p_name,'/',3) = public.mitt_leietaker_id()::text
    else false end
$$;

drop policy if exists filer_select on storage.objects;
drop policy if exists filer_insert on storage.objects;
drop policy if exists filer_delete on storage.objects;
create policy filer_select on storage.objects for select to authenticated
  using (bucket_id = 'filer' and public.kan_lese_fil(name));
create policy filer_insert on storage.objects for insert to authenticated
  with check (bucket_id = 'filer' and public.kan_lese_fil(name));
create policy filer_delete on storage.objects for delete to authenticated
  using (bucket_id = 'filer' and public.min_rolle() in ('admin','forvalter') and public.kan_lese_fil(name));

