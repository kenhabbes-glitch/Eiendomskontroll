create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- Brukerprofiler og tilganger
-- ---------------------------------------------------------------------
create table if not exists public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  epost        text,
  navn         text,
  rolle        text not null default 'ingen'
               check (rolle in ('admin','forvalter','tekniker','leietaker','ingen')),
  leietaker_id uuid,
  aktiv        boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.eiendom_tilgang (
  user_id    uuid not null references public.profiles(id) on delete cascade,
  eiendom_id uuid not null,
  primary key (user_id, eiendom_id)
);

-- ---------------------------------------------------------------------
-- Fagdata. Nøkkelfelt som styrer tilgang ligger i egne kolonner,
-- øvrige felter i data (jsonb) for fleksibilitet.
-- ---------------------------------------------------------------------
create table if not exists public.eiendommer (
  id uuid primary key default gen_random_uuid(),
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);

create table if not exists public.leietakere (
  id uuid primary key default gen_random_uuid(),
  eiendom_id uuid not null references public.eiendommer(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid default auth.uid()
);

alter table public.profiles
  drop constraint if exists profiles_leietaker_fk,
  add constraint profiles_leietaker_fk foreign key (leietaker_id) references public.leietakere(id) on delete set null;
alter table public.eiendom_tilgang
  drop constraint if exists eiendom_tilgang_eiendom_fk,
  add constraint eiendom_tilgang_eiendom_fk foreign key (eiendom_id) references public.eiendommer(id) on delete cascade;

create table if not exists public.systemer (
  id uuid primary key default gen_random_uuid(),
  eiendom_id uuid not null references public.eiendommer(id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
